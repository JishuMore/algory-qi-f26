class Kalman:
    def __init__(self, q, r, kappa, mu=0.0):
        self.q, self.r, self.phi, self.mu = q, r, 1.0 - kappa, mu
        self.x = None
        self.p = 0.0

    def step(self, obs):
        if self.x is None:
            if obs is not None:
                self.x, self.p = obs, self.r
            return self.x
        self.x = self.mu + self.phi * (self.x - self.mu)
        self.p = self.phi * self.phi * self.p + self.q
        if obs is not None:
            k = self.p / (self.p + self.r)
            self.x += k * (obs - self.x)
            self.p *= 1.0 - k
        return self.x


class Model:
    """Causal state for both products; one step() per tick (blackout ticks included)."""

    def __init__(self):
        self.kf_a = Kalman(mu=MU['AMBER'], **KF['AMBER'])
        self.kf_g = Kalman(mu=0.0, **KF['JADE'])
        self.mid_a = []      # raw AMBER mids (None in blackout)
        self.fair_a = []     # filtered AMBER fair
        self.ev = {'AMBER': [], 'JADE': []}
        self.mid = {}        # last observed mid per product
        self.valid = {'AMBER': [], 'JADE': []}   # mids of non-blackout ticks only
        self.jade_base = None

    def smoothed_a(self, j):
        """Best estimate of AMBER fair j ticks ago (centred average of mids when available)."""
        n = len(self.mid_a)
        i = n - 1 - j
        if i < 0:
            return self.fair_a[0] if self.fair_a else MU['AMBER']
        w = min(SMOOTH, j)
        if w >= 2:
            vals = [m for m in self.mid_a[i - w if i >= w else 0:i + w + 1] if m is not None]
            if len(vals) >= w:
                return sum(vals) / len(vals)
        return self.fair_a[i]

    def step(self, mids, events):
        """events[s] = [(age, sign)]; age 1 = trade printed on the previous tick."""
        for s in LIMIT:
            ev = self.ev[s]
            ev.append(0)
            for age, sign in events.get(s, ()):
                if age <= len(ev):
                    ev[-age] = max(-1, min(1, ev[-age] + sign))
            if mids.get(s) is not None:
                self.mid[s] = mids[s]
                self.valid[s].append(mids[s])
        self.mid_a.append(mids.get('AMBER'))
        self.fair_a.append(self.kf_a.step(mids.get('AMBER')))
        if self.fair_a[-1] is not None:
            self.jade_base = MU['JADE'] + JADE_BETA * (self.smoothed_a(JADE_LAG) - MU['AMBER'])
        mj = mids.get('JADE')
        self.kf_g.step(None if mj is None or self.jade_base is None else mj - self.jade_base)
        for lst in (self.mid_a, self.fair_a, self.ev['AMBER'], self.ev['JADE'], self.valid['AMBER'], self.valid['JADE']):
            if len(lst) > HIST:
                del lst[0]

    def buckets(self, s):
        ev = self.ev[s]
        n = len(ev)
        return [sum(ev[-k] for k in range(a, min(b, n) + 1)) for a, b in AGE]

    def lagdiffs(self, s):
        v = self.valid[s]
        return [v[-1] - v[-1 - k] if len(v) > k else 0.0 for k in LAGS]

    def ready(self, s):
        return s in self.mid and self.kf_a.x is not None and (s == 'AMBER' or self.kf_g.x is not None)

    def features(self, s, h):
        fa = self.fair_a[-1]
        if s == 'AMBER':
            return [1.0, fa - MU['AMBER'], self.mid['AMBER'] - fa] + self.buckets('AMBER') + self.lagdiffs('AMBER')
        g = self.kf_g.x
        noise = self.mid['JADE'] - (self.jade_base + g)
        if h < JADE_LAG:
            lead = JADE_BETA * (self.smoothed_a(JADE_LAG - h) - self.smoothed_a(JADE_LAG))
        else:
            lead = JADE_BETA * (fa - self.smoothed_a(JADE_LAG))
        return ([1.0, g, noise, lead, fa - MU['AMBER']] + self.buckets('JADE') + self.buckets('AMBER')
                + self.lagdiffs('JADE') + self.lagdiffs('AMBER'))

    def predict(self, s, h, coef):
        """E[mid_{t+h} - mid_t]."""
        return sum(x * w for x, w in zip(self.features(s, h), coef[s][h]))


def informed_events(market_trades, own_trades, mid_at, fallback_ref, now, seen):
    """Informed-bot trades not seen before, as [(age_in_ticks, +1 buy / -1 sell)].

    Robust to engine differences: each trade is placed by its own timestamp (not assumed to be
    exactly one tick old), re-sent trades are de-duplicated, and the side is judged against the
    mid at the trade's own timestamp. The bot's 7 lots can be split between our resting quote
    (own_trades) and the book (market_trades), so a passive fill of q pairs with a trade of 7 - q.
    """
    groups = {}                                    # (ts, side) -> [market qtys, own passive qty]
    counts = {}
    for kind, lst in (('m', market_trades), ('o', own_trades)):
        for t in lst:
            ts = getattr(t, 'timestamp', None)
            ts = now - 100 if ts is None else ts
            key = (kind, ts, t.price, t.quantity, t.buyer, t.seller)
            n = counts.get(key, 0)
            counts[key] = n + 1
            if key + (n,) in seen:
                continue
            seen[key + (n,)] = ts
            ref = mid_at.get(ts, fallback_ref)
            if ref is None:
                continue
            if kind == 'm':
                g = groups.setdefault((ts, 1 if t.price >= ref else -1), [[], 0])
                g[0].append(t.quantity)
            elif t.seller == 'SUBMISSION' and t.price > ref:     # bot bought from our ask
                groups.setdefault((ts, 1), [[], 0])[1] += t.quantity
            elif t.buyer == 'SUBMISSION' and t.price < ref:      # bot sold into our bid
                groups.setdefault((ts, -1), [[], 0])[1] += t.quantity
    for k in [k for k, ts in seen.items() if ts < now - 100 * HIST]:
        del seen[k]
    out = []
    for (ts, side), (qs, own) in groups.items():
        if (any(q >= INFORMED_QTY for q in qs) or own >= INFORMED_QTY
                or (0 < own < INFORMED_QTY and (INFORMED_QTY - own) in qs)):
            out.append((max(1, (now - ts) // 100), side))
    return out


class Trader:
    def __init__(self):
        self.model = Model()
        self.prev_mid = {}
        self.mid_at = {s: {} for s in LIMIT}        # timestamp -> mid, for judging trade side
        self.seen = {s: {} for s in LIMIT}          # de-dup keys of trades already processed
        self.live_ticks = 0
        self.last_event = 0                         # live tick of the most recent informed trade
        self.names = set()
        self.log = True
        # execution parameters (cross-day grid, research/grid_product.py; picked mid-plateau)
        self.take_h = {'AMBER': 12, 'JADE': 10}     # forecast horizon used for taking
        self.make_h = {'AMBER': 12, 'JADE': 10}     # forecast horizon used for quoting
        self.take_edge = {'AMBER': 1.25, 'JADE': 1.0}
        self.make_edge = {'AMBER': 2.0, 'JADE': 2.0}
        self.skew = {'AMBER': 0.04, 'JADE': 0.02}

    def run(self, state):
        now = state.timestamp
        mids, events = {}, {}
        for s in LIMIT:
            d = state.order_depths.get(s)
            mids[s] = (max(d.buy_orders) + min(d.sell_orders)) / 2.0 if d and d.buy_orders and d.sell_orders else None
            events[s] = informed_events(state.market_trades.get(s, []), state.own_trades.get(s, []),
                                        self.mid_at[s], self.prev_mid.get(s), now, self.seen[s])
        self.model.step(mids, events)
        if all(mids[s] is not None for s in LIMIT):
            self.live_ticks += 1
        if any(events[s] for s in LIMIT):
            self.last_event = self.live_ticks
        noev = self.live_ticks >= NOEV_TICKS and self.live_ticks - self.last_event >= NOEV_TICKS
        coef = COEF_NOEV if noev and COEF_NOEV else COEF

        result = {}
        for s in LIMIT:
            d = state.order_depths.get(s) or OrderDepth()
            if mids[s] is None:
                continue                      # blackout: no market trades ever print, so quotes cannot fill
            self.prev_mid[s] = mids[s]
            self.mid_at[s][now] = mids[s]
            self.mid_at[s].pop(now - 100 * HIST, None)
            if not self.model.ready(s) or not coef:
                continue
            pos = state.position.get(s, 0)
            m = mids[s]
            take_val = m + self.model.predict(s, self.take_h[s], coef) - self.skew[s] * pos
            make_val = m + self.model.predict(s, self.make_h[s], coef) - self.skew[s] * pos
            result[s] = self.orders_for(s, d, pos, LIMIT[s], take_val, make_val)
        if self.log:
            self.print_log(state, mids, events, noev)
        return result, 0, ''

    def print_log(self, state, mids, events, noev):
        """One compact line per tick: ts|mode|per product: pos, mid, market trades (qty@price/age), own fills, events."""
        now = state.timestamp
        if now == 0:
            print('LOG ts|mode|SYM pos mid m[qty@px/dt..] o[n] e[(age,sign)..]   dt = trade ts - now in ticks')
        parts = [str(now), 'NOEV' if noev else 'EV']
        for s in LIMIT:
            mt = state.market_trades.get(s, [])
            for t in mt:
                for nm in (t.buyer, t.seller):
                    if nm and nm not in self.names:
                        self.names.add(nm)
                        print(f'NEW_NAME {nm} {s} ts={getattr(t, "timestamp", None)}')
            trades = ','.join(f'{t.quantity}@{t.price}/{(getattr(t, "timestamp", now) - now) // 100}' for t in mt[:6])
            parts.append(f'{s[0]} {state.position.get(s, 0)} {mids[s]} m[{trades}] o{len(state.own_trades.get(s, []))} e{events[s]}')
        print('|'.join(parts))

    def orders_for(self, s, d, pos, lim, take_val, make_val):
        orders = []
        buy_cap = lim - pos
        sell_cap = lim + pos
        te = self.take_edge[s]
        me = self.make_edge[s]
        for price in sorted(d.sell_orders):
            if price > take_val - te or buy_cap <= 0:
                break
            q = min(-d.sell_orders[price], buy_cap)
            orders.append(Order(s, price, q))
            buy_cap -= q
        for price in sorted(d.buy_orders, reverse=True):
            if price < take_val + te or sell_cap <= 0:
                break
            q = min(d.buy_orders[price], sell_cap)
            orders.append(Order(s, price, -q))
            sell_cap -= q

        best_bid = max(d.buy_orders)
        best_ask = min(d.sell_orders)
        bid = min(best_bid + 1, int(math.floor(make_val - me)))
        ask = max(best_ask - 1, int(math.ceil(make_val + me)))
        if bid >= ask:
            bid = ask - 1
        if buy_cap > 0 and bid < best_ask:
            orders.append(Order(s, bid, buy_cap))
        if sell_cap > 0 and ask > best_bid:
            orders.append(Order(s, ask, -sell_cap))
        return orders
