"""AMBER / JADE trader: structural fair-value model + linear multi-horizon forecasts.

Market structure (estimated from days -2/-1, see research/):
  * Every book level is centred on a latent fair value F plus a common iid shock
    (sd ~1.55 AMBER, ~1.02 JADE). Mid-price diffs therefore have lag-1 autocorr ~ -0.27.
    We remove the shock with a Kalman filter instead of raw lag differences.
  * F mean-reverts slowly to 1000 / 500 (kappa ~ 0.01 per tick).
  * An informed bot trades exactly 7 lots (min 20 ticks between its trades). After its
    trade the fair drifts ~0.35/tick in the same direction for ~30 ticks (+10..13 total).
  * JADE = 500 + 0.5 * (AMBER_fair[t-25] - 1000) + G, G an independent OU with its own
    informed pulses. So JADE's next h <= 25 ticks of AMBER-driven move are already observed.
Forecasts E[mid_{t+h} - mid_t] are linear in these structural features plus multi-scale lag
diffs (past moves partly revert); coefficients come from research/fit.py (ridge, fit on both
days, cross-day validated). Execution: take when the book is through the forecast value by
take_edge, otherwise quote one tick inside the touch, with linear inventory skew. ~95% of the
volume is taken (cost ~3.4/lot AMBER), so execution parameters stay conservative.
"""
